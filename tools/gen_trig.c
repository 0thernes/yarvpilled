/* Regenerates ext/yarvpilled_native/trig_table.h and lib/yarvpilled/trig_table.rb.
 * Run from the repo root on glibc: cc -o /tmp/gen_trig tools/gen_trig.c -lm && /tmp/gen_trig */
#include <stdio.h>
#include <math.h>
#include <string.h>
#include <stdint.h>
int main(void){
  FILE *h=fopen("ext/yarvpilled_native/trig_table.h","w"), *r=fopen("lib/yarvpilled/trig_table.rb","w");
  fprintf(h,"/* Generated once by tools/gen_trig.c from glibc cos/sin(2*pi*k/64) (correctly rounded).\n * Literal bit patterns, so every platform and backend uses identical directions\n * regardless of its libm. lib/yarvpilled/trig_table.rb holds the same bits. */\n#ifndef YP_TRIG_TABLE_H\n#define YP_TRIG_TABLE_H\n#include <stdint.h>\nstatic const uint64_t YP_COS_BITS[64] = {\n");
  fprintf(r,"# frozen_string_literal: true\n\n# Generated by tools/gen_trig.c: IEEE-754 bit patterns of cos/sin(2*pi*k/64), identical to\n# ext/yarvpilled_native/trig_table.h, so directions never depend on the platform libm.\nmodule Yarvpilled\n  module TrigTable\n    COS_BITS = [\n");
  for(int t=0;t<2;t++){
    if(t==1){fprintf(h,"};\nstatic const uint64_t YP_SIN_BITS[64] = {\n"); fprintf(r,"    ].freeze\n    SIN_BITS = [\n");}
    for(int k=0;k<64;k++){double v=t?sin(2.0*M_PI*k/64.0):cos(2.0*M_PI*k/64.0); uint64_t b; memcpy(&b,&v,8);
      fprintf(h,"  0x%016llxULL,%s",(unsigned long long)b,(k%4==3)?"\n":""); fprintf(r,"%s0x%016llx,%s",(k%4==0)?"      ":" ",(unsigned long long)b,(k%4==3)?"\n":"");}
  }
  fprintf(h,"};\n#endif\n"); fprintf(r,"    ].freeze\n    COS = COS_BITS.map { [_1].pack(\"Q<\").unpack1(\"E\") }.freeze\n    SIN = SIN_BITS.map { [_1].pack(\"Q<\").unpack1(\"E\") }.freeze\n  end\nend\n");
  fclose(h); fclose(r); return 0; }
